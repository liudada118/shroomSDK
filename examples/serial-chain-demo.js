#!/usr/bin/env node

const {
  MemoryCaptureStore,
  ShroomSensorSDK,
} = require('..');

function parseArgs(argv) {
  const options = {
    capture: 'memory',
    channel: 'sit',
    durationMs: 15000,
    maxFrames: 20,
    sensorType: 'hand0205',
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];
    if (arg === '--sensor') {
      options.sensorType = next;
      index += 1;
    } else if (arg === '--port') {
      options.port = next;
      index += 1;
    } else if (arg === '--channel') {
      options.channel = next;
      index += 1;
    } else if (arg === '--duration') {
      options.durationMs = Number(next) || options.durationMs;
      index += 1;
    } else if (arg === '--max-frames') {
      options.maxFrames = Number(next) || options.maxFrames;
      index += 1;
    } else if (arg === '--capture') {
      options.capture = next || options.capture;
      index += 1;
    } else if (arg === '--capture-name') {
      options.captureName = next;
      index += 1;
    } else if (arg === '--db-dir') {
      options.dbDir = next;
      index += 1;
    } else if (arg === '--mock') {
      options.mock = true;
    } else if (arg === '--list-ports') {
      options.listPorts = true;
    } else if (arg === '--help') {
      options.help = true;
    }
  }

  return options;
}

function printHelp() {
  console.log(`
Usage:
  npm run sdk:serial-demo -- --port COM3 [options]

Real serial chain:
  npm run sdk:serial-demo -- --sensor hand0205 --channel sit --port COM3

List ports:
  npm run sdk:serial-demo -- --list-ports

No hardware smoke test:
  npm run sdk:serial-demo -- --mock

Options:
  --sensor hand0205        Sensor profile name. Default: hand0205
  --channel sit            Channel name for this serial port. Default: sit
  --port COM3              Serial port path
  --duration 15000         Stop after milliseconds. Default: 15000
  --max-frames 20          Stop after parsed frame count. Default: 20
  --capture memory|none    Capture parsed frames. Default: memory
  --capture-name demo      Capture name
  --db-dir ./db            Reserved for db capture stores
  --list-ports             Print serial port candidates
  --mock                   Run the same parse/capture path with generated bytes
`);
}

function createSdk(options = {}) {
  return new ShroomSensorSDK({
    dbDir: options.dbDir,
    store: options.capture === 'none' ? null : new MemoryCaptureStore(),
  });
}

async function listPorts(sdk) {
  const ports = await sdk.listPorts();
  console.log('[serial-demo] ports:', ports);
  return ports;
}

function buildMockFrame(profile) {
  const pressureLength = Number(profile.pressureLength) > 0 ? Number(profile.pressureLength) : 256;
  const rotateLength = Number(profile.rotateLength) > 0 ? Number(profile.rotateLength) : 4;
  const values = [];
  for (let index = 0; index < pressureLength; index += 1) {
    values.push(index % 64);
  }
  for (let index = 0; index < rotateLength; index += 1) {
    values.push(index + 1);
  }
  return Buffer.from(values);
}

function logFrame(frameCount, frame) {
  console.log('[serial-demo] frame:', {
    channel: frame.channel,
    matrix: frame.matrix,
    max: frame.stats?.max,
    nonZeroCount: frame.stats?.nonZeroCount,
    rawLength: frame.rawLength,
    sensorType: frame.sensorType,
    timestamp: frame.timestamp,
  });
}

async function runMock(options) {
  const sdk = createSdk(options);
  const profile = sdk.registry.getProfile(options.sensorType);
  const rawFrame = buildMockFrame(profile);
  const capture = options.capture === 'none'
    ? null
    : sdk.getStore().createCapture({
      name: options.captureName || `mock_${options.sensorType}_${Date.now()}`,
      sensorType: options.sensorType,
      hz: 12,
      metadata: { mode: 'mock', channel: options.channel },
    });

  const frame = sdk.zeroCalibrator.apply(sdk.registry.parse(options.sensorType, rawFrame, {
    channel: options.channel,
    profile,
  }));

  if (capture) {
    sdk.getStore().insertFrame({
      captureId: capture.id,
      sensorType: options.sensorType,
      channel: options.channel,
      rawFrame,
      frame,
    });
  }

  logFrame(1, frame);
  console.log('[serial-demo] mock done:', {
    capture,
    capturedFrames: capture ? sdk.getStore().queryFrames({ captureId: capture.id }).length : 0,
  });
  sdk.close();
}

async function runSerial(options) {
  const sdk = createSdk(options);
  if (options.listPorts) {
    await listPorts(sdk);
    sdk.close();
    return;
  }

  if (!options.port) {
    const ports = await listPorts(sdk);
    const likely = ports.find((port) => port.isLikelySensorPort) || ports[0];
    if (!likely?.path) {
      throw new Error('no serial port found; pass --port COMx or run --mock');
    }
    options.port = likely.path;
    console.log('[serial-demo] auto selected port:', options.port);
  }

  const session = await sdk.open({
    sensorType: options.sensorType,
    channels: {
      [options.channel]: options.port,
    },
  });

  let frameCount = 0;
  let capture = null;
  if (options.capture !== 'none') {
    capture = sdk.startCapture(session, {
      name: options.captureName || `serial_${options.sensorType}_${Date.now()}`,
      hz: 12,
      metadata: {
        mode: 'serial',
        channel: options.channel,
        port: options.port,
      },
    });
    console.log('[serial-demo] capture started:', capture);
  }

  session.on('channelOpen', (event) => console.log('[serial-demo] channel open:', event));
  session.on('rawFrame', (event) => {
    if (frameCount < 3) {
      console.log('[serial-demo] raw frame:', {
        channel: event.channel,
        rawLength: event.rawFrame.length,
      });
    }
  });
  session.on('frame', async (frame) => {
    frameCount += 1;
    if (frameCount <= 5 || frameCount === options.maxFrames) {
      logFrame(frameCount, frame);
    }
    if (frameCount >= options.maxFrames) {
      await stop();
    }
  });
  session.on('error', (event) => {
    console.error('[serial-demo] serial error:', event.error?.message || event.error || event);
  });

  let stopped = false;
  async function stop() {
    if (stopped) return;
    stopped = true;
    if (capture) {
      sdk.stopCapture(session);
      const capturedFrames = sdk.getStore().queryFrames({ captureId: capture.id }).length;
      console.log('[serial-demo] capture stopped:', { id: capture.id, capturedFrames });
    }
    await session.close();
    sdk.close();
    console.log('[serial-demo] done:', { frameCount });
  }

  console.log('[serial-demo] serial chain running:', {
    sensorType: options.sensorType,
    channel: options.channel,
    port: options.port,
    durationMs: options.durationMs,
    maxFrames: options.maxFrames,
  });

  setTimeout(() => {
    stop().catch((error) => {
      console.error('[serial-demo] stop failed:', error.message || error);
      process.exitCode = 1;
    });
  }, options.durationMs);
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    printHelp();
    return;
  }

  if (options.mock) {
    await runMock(options);
    return;
  }

  await runSerial(options);
}

if (require.main === module) {
  main().catch((error) => {
    console.error('[serial-demo] failed:', error.message || error);
    process.exit(1);
  });
}

module.exports = {
  buildMockFrame,
  createSdk,
  parseArgs,
  runMock,
};
