/** 掩码里「这里是手」的填充值。原实现写死 5，管线后面按 `< 50`（×10 后）判定。 */
export const MASK_VALUE = 5;

/**
 * 按关节点表铺出手形掩码（`hand0205` 预设）。
 *
 * 逐段对应 `hand0205Point.jsx:480-553` 的五个循环，**顺序和越界行为都照抄**：
 *
 * | 段 | 覆盖的表项 | 盖法 |
 * | :--- | :--- | :--- |
 * | 四指头 | 每行 `j ∈ [0,6)`，前 3 行 | 沿行 +0..+4 共 5 格 |
 * | 小指侧 | 每行 `j ∈ [6,8)`，前 3 行 | 同上；第 3 行额外补 +5 行的 3 格（向左） |
 * | 拇指 | 每行 `j ∈ [8,10)`，前 3 行 | +0 行向左 4 格 + (+1) 行向左 2 格 |
 * | 指根 | 表项 30..45 | +0/+1/+2 行 × 当前列与左邻列 |
 * | 掌心 | 表项 46..95 | +0 行左右各 1 格 + (+1) 行左右各 1 格 |
 *
 * ⚠️ **这里一处边界检查都没有**：`put()` 直接算 `row * size + col`，`col - 1/-2/-3`
 * 为负就跨到上一行的行尾，`row + 4/+5` 超出行数就把数组撑长。搬进来时**没有补检查**
 * —— 补了就是画面变化。
 *
 * 不过实测两张随包点表都不会真的踩到：写入范围是行 0..26（`GLOVES_POINTS`）/
 * 2..27（`GLOVES_POINTS_ALT`）、列 4..28 / 2..28，508 次写入全部落在 32×32 内
 * （见 `layout.test.js` 里钉这个范围的那条）。所以「不补检查」的代价只落在二开者
 * 自带点表的场合，而那时候正确的行为恰恰是照原样跑，别替他兜底。
 *
 * 另外表项 30..45 那段的循环上界写的是 `30 + 8 * 2`，掌心段起点写的是
 * `3 * 10 + 2 * 8` —— 两个都是 46，原实现两种写法并存，照抄。
 *
 * 最后整体逆时针转 90°（`rotate90CCW`，32×32）。
 *
 * @param {number[][]} pointTable 关节点表，`GLOVES_POINTS` 或 `GLOVES_POINTS_ALT`。
 * @param {(arr: number[], height: number, width: number) => number[]} rotate90CCW
 *   旋转函数，由调用方注入（`core/frameMath.js` 的那个）—— 注入而不是 import
 *   是为了让这个文件保持「只有数据和循环」，测试里可以传 `(a) => a` 单看盖点结果。
 * @param {number} [size=32] 矩阵边长。
 * @returns {number[]} 长度 `size * size` 的掩码数组，手形区域为 5。
 */
export function buildGlovesMask(pointTable, rotate90CCW, size = 32) {
  const mask = new Array(size * size).fill(0);
  const put = (row, col) => { mask[row * size + col] = MASK_VALUE; };

  // 四指头
  for (let i = 0; i < 3; i += 1) {
    for (let j = 0; j < 6; j += 1) {
      const [row, col] = pointTable[i * 10 + j];
      for (let d = 0; d <= 4; d += 1) put(row + d, col);
    }
  }

  // 小指侧
  for (let i = 0; i < 3; i += 1) {
    for (let j = 6; j < 8; j += 1) {
      const [row, col] = pointTable[i * 10 + j];
      for (let d = 0; d <= 4; d += 1) put(row + d, col);
      if (i === 2) {
        put(row + 5, col);
        put(row + 5, col - 1);
        put(row + 5, col - 2);
      }
    }
  }

  // 拇指
  for (let i = 0; i < 3; i += 1) {
    for (let j = 8; j < 10; j += 1) {
      const [row, col] = pointTable[i * 10 + j];
      put(row, col);
      put(row, col - 1);
      put(row, col - 2);
      put(row, col - 3);
      put(row + 1, col);
      put(row + 1, col - 1);
    }
  }

  // 指根
  for (let i = 30; i < 30 + 8 * 2; i += 1) {
    const [row, col] = pointTable[i];
    put(row, col);
    put(row + 1, col);
    put(row + 2, col);
    put(row, col - 1);
    put(row + 1, col - 1);
    put(row + 2, col - 1);
  }

  // 掌心
  for (let i = 3 * 10 + 2 * 8; i < 3 * 10 + 2 * 8 + 5 * 10; i += 1) {
    const [row, col] = pointTable[i];
    put(row, col);
    put(row + 1, col + 1);
    put(row + 1, col - 1);
    put(row, col + 1);
    put(row, col - 1);
  }

  return rotate90CCW(mask, size, size);
}

/**
 * 按传感点表铺出手形掩码（`hand0205_147` 预设）。
 *
 * 逐字对应 `hand0205Point147.jsx:568-578`：每个点写自己和下一行，列下标取
 * `31 - col`（**左右镜像烘进了下标**，所以这条路径不需要 `rotate90`）。
 *
 * ⚠️ `size` 不是 32 时那个 `31` 也要跟着变，这里写成 `size - 1`；
 * 唯一的调用点传的就是 32，与原实现同值。
 *
 * @param {number[][]} pointTable 传感点表，`HAND_POINT_ARR_147`。
 * @param {number} [size=32] 矩阵边长。
 * @returns {number[]} 长度 `size * size` 的掩码数组，手形区域为 5。
 */
export function buildHandPointMask147(pointTable, size = 32) {
  const mask = new Array(size * size).fill(0);
  pointTable.forEach((a) => {
    mask[a[0] * size + (size - 1 - a[1])] = MASK_VALUE;
    mask[(a[0] + 1) * size + (size - 1 - a[1])] = MASK_VALUE;
  });
  return mask;
}

