/**
 * renderers/handPoints/core/layout.js - 手形掩码：两张写死的点表 + 两套盖点循环
 *
 * 手套的 32×32 矩阵里只有一部分格子底下真有传感器，其余是空的。渲染时要把「不是手」
 * 的那些点沉到画面外去（`positions.y = -100000`），靠的就是这里生成的**掩码**：
 * 一张同样 32×32、手形区域填 5、其余填 0 的数组。它随后走和压力数据完全一样的
 * 插值 + 补边 + 高斯模糊管线，得到一张边缘柔和的手形遮罩。
 *
 * ## 两张点表不是同一张表的两个版本
 *
 * - `GLOVES_POINTS` / `GLOVES_POINTS_ALT`（各 96 项）配 `buildGlovesMask()`：
 *   点表记的是**关节位置**，靠五段盖点循环把每个关节沿指向铺成一条手指，最后整体
 *   逆时针转 90°。这是 `hand0205` 预设。
 * - `HAND_POINT_ARR_147`（147 项，名字里的 147 就是这个数）配
 *   `buildHandPointMask147()`：点表记的是**每个
 *   传感点本身**，盖点循环只往下补一行，镜像（`31 - col`）直接烘进了取下标的式子里，
 *   **没有 `rotate90` 那一步**。这是 `hand0205_147` 预设。
 *
 * 所以两者不能互换点表 —— 换了画面就是一团乱码，不是「另一种手」。
 *
 * ## 关于 `GLOVES_POINTS_ALT`
 *
 * 原实现里它叫 `glovesPoints1`，**定义了但从没被读过** —— 只有一行注释掉的
 * `glovesPoints = glovesPoints1` 会启用它。搬进来时把它做成了 `pointTable` 参数的
 * 一个合法取值（预设 `hand0205Alt`），于是那行注释从「改源码才能试」变成「换个预设
 * 就能试」。这是本轮唯一一处把死代码转成活配置的地方，其余死代码一律直接删。
 */

