/** 每次返回独立快照；row/col 是 14×8 原始点表的零基索引，并非扫描矩阵坐标。 */
export function createInsoleLayout(side) {
  const sourceIndices = new Uint16Array(112);
  const positions = [];
  INSOLE_SOURCE_ROWS.forEach((row, b) => row.forEach(([dc, xMm, yMm], col) => {
    const scanRow = side === 'right' ? 8 - dc : dc + 7;
    const scanCol = side === 'right' ? 2 + b : 13 - b;
    sourceIndices[b * 8 + col] = scanRow * 16 + scanCol;
    positions.push({ row: b, col, xMm, yMm });
  }));
  return { rows: 14, cols: 8, sourceIndices, positions };
}
